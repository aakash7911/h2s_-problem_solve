/**
 * Generates a clean, professional text/markdown Event Brief for sharing with stakeholders
 */
export function generateEventBrief(plan: EventPlan): string {
  const req = plan.requirements;
  const b = plan.budget;

  return `# EVENT BRIEF: ${req.title.toUpperCase()}
Generated by EventWise AI Platform
Plan Date: ${new Date().toLocaleDateString()} | Target Event Date: ${req.date} (${req.startTime}, ${req.durationHours} hours)
=============================================================

1. EVENT OVERVIEW
-----------------
* Type: ${req.eventType.replace('_', ' ').toUpperCase()}
* Theme / Vibe: ${req.theme}
* Location / Venue: ${req.location} (${req.venueType.toUpperCase()})
* Headcount: ${req.guestCount} guests
* Planning Priority: ${req.priority.replace('_', ' ')}
* Risk Tolerance: ${req.riskTolerance}
* Dietary Needs: ${req.dietaryRequirements.join(', ') || 'Standard banquet'}
* Accessibility Needs: ${req.accessibilityRequirements.join(', ') || 'Standard step-free entrance'}

2. BUDGET SUMMARY
-----------------
* Total Planned Budget: ${b.currency} ${b.totalBudget.toLocaleString()}
* Total Estimated Expenses: ${b.currency} ${b.totalEstimatedCost.toLocaleString()}
* Emergency Contingency Reserve (${b.contingencyPercentage}%): ${b.currency} ${b.contingencyReserve.toLocaleString()}
* Remaining Unallocated Buffer: ${b.currency} ${b.remainingBudget.toLocaleString()}
* Budget Health Status: ${b.budgetPressureLevel.toUpperCase()}
  Explanation: ${b.budgetPressureReason}

3. TIMELINE & RUN OF SHOW
-------------------------
${plan.schedule.map((s) => `* [${s.startTime} - ${s.endTime}] ${s.title} (${s.durationMinutes}m)${s.responsibleParty ? ` — Lead: ${s.responsibleParty}` : ''}`).join('\n')}

4. CRITICAL ACTION ITEMS & MILESTONES
-------------------------------------
${plan.tasks.map((t) => `* [${t.isCompleted ? 'DONE' : 'PENDING'}] ${t.title} (Due: ${t.deadlineDate})`).join('\n')}

5. TOP RISKS & CONTINGENCY PLAYBOOKS
------------------------------------
${plan.risks.slice(0, 3).map((r) => `* ${r.title} [Score: ${r.riskScore}/9]
  Plan: ${r.contingencyPlan}`).join('\n')}

=============================================================
* Note: Prepared with EventWise AI deterministic constraint calculations.
`;
}
